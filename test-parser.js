const assert = require("node:assert/strict");
const { normalizeText, parseReminder } = require("./parser.js");

const reference = new Date("2026-10-04T10:00:00+08:00");
const cases = [
  ["10分鐘後提醒我喝水", "喝水", "2026-10-04T02:10:00.000Z"],
  ["十分鐘後提醒我喝水", "喝水", "2026-10-04T02:10:00.000Z"],
  ["半小時後提醒我出門", "出門", "2026-10-04T02:30:00.000Z"],
  ["一個小時後提醒我打電話", "打電話", "2026-10-04T03:00:00.000Z"],
  ["一個半小時後提醒我開會", "開會", "2026-10-04T03:30:00.000Z"],
  ["兩小時後提醒我回覆客戶", "回覆客戶", "2026-10-04T04:00:00.000Z"],
  ["今天下午三點提醒我回覆客戶", "回覆客戶", "2026-10-04T07:00:00.000Z"],
  ["今天下午三點半提醒我回覆客戶", "回覆客戶", "2026-10-04T07:30:00.000Z"],
  ["明天早上八點提醒我買早餐", "買早餐", "2026-10-05T00:00:00.000Z"],
  ["明早八點提醒我買早餐", "買早餐", "2026-10-05T00:00:00.000Z"],
  ["明早提醒我買早餐", "買早餐", "2026-10-05T00:00:00.000Z"],
  ["明晚提醒我運動", "運動", "2026-10-05T11:00:00.000Z"],
  ["下週一早上九點提醒我開會", "開會", "2026-10-05T01:00:00.000Z"],
  ["這禮拜五下午三點提醒我交報告", "交報告", "2026-10-02T07:00:00.000Z"],
  ["等一下提醒我喝水", "喝水", "2026-10-04T02:10:00.000Z"],
  ["待會提醒我喝水", "喝水", "2026-10-04T02:10:00.000Z"],
  ["晚一點提醒我回訊息", "回訊息", "2026-10-04T03:00:00.000Z"],
  ["睡前提醒我吃藥", "吃藥", null],
];

assert.equal(normalizeText("１２點鐘，十五分"), "12點15分鐘");
assert.equal(normalizeText("兩個小時後"), "2小時後");

for (const [input, expectedName, expectedIso] of cases) {
  const result = parseReminder(input, reference);
  assert.equal(result.taskName, expectedName, input);
  assert.equal(result.reminderAt?.toISOString() || null, expectedIso, input);
}

console.log(`通過 ${cases.length} 組時間解析測試`);
